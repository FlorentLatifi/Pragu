import type { BenchResult, Miss } from './evaluate.js';
import { ERROR_RULE_MIN_PRECISION } from './gate.js';
import { formatMetric } from './metrics.js';

function gateCell(rule: BenchResult['rules'][number]): string {
  if (rule.severity !== 'error') return '–';
  return rule.precision !== null && rule.precision >= ERROR_RULE_MIN_PRECISION ? 'pass' : '**below 0.90**';
}

function missLine(miss: Miss): string {
  const detail = [miss.note, miss.message].filter((part) => part !== undefined).join(' — ');
  return `- \`${miss.rule}\` on \`${miss.element}\` (${miss.fixture} › ${miss.screen})${detail === '' ? '' : `: ${detail}`}`;
}

/** The published results page (docs/bench/results.md). Deterministic, so it diffs cleanly. */
export function renderMarkdown(result: BenchResult): string {
  const rows = result.rules.map(
    (rule) =>
      `| \`${rule.rule}\` | ${rule.severity} | ${String(rule.tp)} | ${String(rule.fp)} | ${String(rule.fn)} | ${String(rule.tn)} | ${formatMetric(rule.precision)} | ${formatMetric(rule.recall)} | ${formatMetric(rule.f1)} | ${formatMetric(rule.mcc)} | ${gateCell(rule)} |`,
  );
  const section = (title: string, misses: Miss[]) =>
    `## ${title}\n\n${misses.length === 0 ? 'None.' : misses.map(missLine).join('\n')}\n`;
  const awaiting =
    result.awaiting.length === 0
      ? 'None.'
      : result.awaiting
          .map(
            (entry) =>
              `- \`${entry.rule}\`: ${String(entry.barriers)} barriers, ${String(entry.correctTwins)} correct twins labelled`,
          )
          .join('\n');

  return `# Pragu Bench results

Generated by \`pnpm bench:update\` from ${String(result.screens)} recorded screens in ${result.fixtures.map((f) => `\`${f}\``).join(', ')}. Counts are exact; ratios are truncated, never rounded up. True negatives count only labelled correct twins, so precision and recall are the numbers to read. A small bench gives wide uncertainty: treat these as early signals, not final quality figures.

| Rule | Severity | TP | FP | FN | TN | Precision | Recall | F1 | MCC | Error-rule bar (precision ≥ ${ERROR_RULE_MIN_PRECISION.toFixed(2)}) |
|---|---|---|---|---|---|---|---|---|---|---|
${rows.join('\n')}

${section('False positives', result.falsePositives)}
${section('False negatives', result.falseNegatives)}
## Labelled rules awaiting implementation

${awaiting}
`;
}
