// Turns the report's WOFF2 files into @font-face rules in packages/report/src/fonts.ts,
// so the report stays one offline file. Run after changing a font: node scripts/embed-fonts.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const fontsDir = fileURLToPath(new URL('../packages/report/fonts/', import.meta.url));
const output = fileURLToPath(new URL('../packages/report/src/fonts.ts', import.meta.url));

const faces = [
  ['Atkinson Hyperlegible Next', 'atkinson-hyperlegible-next', 400],
  ['Atkinson Hyperlegible Next', 'atkinson-hyperlegible-next', 700],
  ['Atkinson Hyperlegible Mono', 'atkinson-hyperlegible-mono', 400],
  ['Atkinson Hyperlegible Mono', 'atkinson-hyperlegible-mono', 700],
];

const rules = faces.map(([family, file, weight]) => {
  const base64 = readFileSync(`${fontsDir}${file}-latin-${weight}-normal.woff2`).toString('base64');
  return `@font-face{font-family:"${family}";font-style:normal;font-weight:${weight};font-display:swap;src:url(data:font/woff2;base64,${base64}) format("woff2");}`;
});

writeFileSync(
  output,
  `// Generated by scripts/embed-fonts.mjs from packages/report/fonts (SIL Open Font License 1.1). Do not edit.\nexport const FONT_FACES = ${JSON.stringify(rules.join(''))};\n`,
);
console.log(`Wrote ${output} (${String(Math.round(rules.join('').length / 1024))} KB).`);
