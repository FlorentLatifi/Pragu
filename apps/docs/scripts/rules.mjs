// Writes one page per rule from the rule metadata in @pragu/core (the brief: the rules
// reference is generated, so it cannot drift from what the tool says). Run before astro.
import { mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const { defaultRules } = await import('@pragu/core');
const results = JSON.parse(await readFile(new URL('../../../bench/results.json', import.meta.url), 'utf8'));
const dir = fileURLToPath(new URL('../src/content/docs/rules/', import.meta.url));
await rm(dir, { recursive: true, force: true });
await mkdir(dir, { recursive: true });

const quote = (text) => JSON.stringify(text);
// Fix texts hold code such as <Pressable …>, which Markdown would read as HTML.
const md = (text) => text.replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;');
const metric = (value) => (value === null ? 'n/a' : value.toFixed(2));

for (const [index, { meta }] of defaultRules.entries()) {
  const bench = results.rules.find((rule) => rule.rule === meta.id);
  const standards = meta.wcag.length === 0 ? 'Best practice (no WCAG success criterion)' : `WCAG 2.2: ${meta.wcag.join(', ')}`;
  const en = meta.en301549.length === 0 ? '' : ` · EN 301 549: ${meta.en301549.join(', ')}`;
  const measured =
    bench === undefined
      ? 'Not measured on Pragu Bench yet.'
      : `On the seeded fixtures: ${bench.tp} true and ${bench.fp} false positives, ${bench.fn} missed (precision ${metric(bench.precision)}, recall ${metric(bench.recall)}). A small sample: an early signal, not a quality claim.`;
  const page = `---
title: ${quote(meta.id)}
description: ${quote(meta.title)}
sidebar:
  order: ${index + 1}
---

<!-- Generated by apps/docs/scripts/rules.mjs from the rule's metadata. Edit the rule, not this page. -->

**${md(meta.title)}.** ${meta.severity[0].toUpperCase()}${meta.severity.slice(1)}, ${meta.confidence} confidence. ${standards}${en}.

## Who it affects

${md(meta.whoIsAffected)}

## What they experience

${md(meta.whatTheyExperience)}

## How to fix it

- **React Native:** ${md(meta.fix.reactNative)}
- **Jetpack Compose:** ${md(meta.fix.compose)}
- **Android Views:** ${md(meta.fix.androidViews)}

## How well it works

${measured}

Run \`pragu rules --explain ${meta.id}\` for the same text in a terminal.
`;
  await writeFile(`${dir}${meta.id.replace('/', '-')}.md`, page);
}
console.log(`Wrote ${defaultRules.length} rule pages.`);
